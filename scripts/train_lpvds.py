#!/usr/bin/env python
"""Train the LPV-DS policy on all usable cycles and document it.

Fits one stable LPV-DS per primitive in its goal frame (approach: cube frame; transport: box
frame), checks the Lyapunov condition numerically, integrates the field from every demonstrated
start (3-D), and draws 2-D slices of the field with the Lyapunov level sets.

Writes outputs/models/lpv_ds.json, docs/lpvds_report.md and docs/figures/lpvds_field.png.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "1")

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from so101_tpgmm.config import load_config, resolve_path  # noqa: E402
from so101_tpgmm.data.lerobot_dataset import LeRobotV3Dataset  # noqa: E402
from so101_tpgmm.kinematics.fk import SO101Kinematics  # noqa: E402
from so101_tpgmm.lpvds.policy import FRAME, LPVDSPolicy  # noqa: E402
from so101_tpgmm.tpgmm.demos import build_demos, training_table  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=None)
    ap.add_argument("--set", nargs="*", default=[])
    args = ap.parse_args()
    cfg = load_config(args.config, args.set)
    ds = LeRobotV3Dataset(resolve_path(cfg["dataset"]["local_dir"]), cfg["dataset"]["state_key"])
    kin = SO101Kinematics(resolve_path(cfg["kinematics"]["urdf"]))
    df = training_table(pd.read_csv(resolve_path(cfg["segmentation"]["output_csv"])),
                        pd.read_csv(resolve_path(cfg["vision"]["frames_csv"])), cfg["tpgmm"]["exclude_aborted"])
    demos, ctx = build_demos(df, ds, kin, cfg, ["approach_grasp", "transport_release"])
    pol = LPVDSPolicy.fit(demos, ctx)
    pol.save(resolve_path(cfg["tpgmm"]["models_dir"]) / "lpv_ds.json")

    stats = {}
    fig, axs = plt.subplots(2, 2, figsize=(14, 11))
    for row, name in enumerate(pol.primitives):
        p = pol.prims[name]
        m = p.pos
        lyap = max(float(np.linalg.eigvalsh(m.A[k].T @ m.P + m.P @ m.A[k]).max()) for k in range(len(m.A)))
        L = [d.local()[FRAME[name]][:, 1:4] for d in demos[name]]
        ends = []
        for tr in L:  # integrate the (unscaled) field from each demonstrated start
            x = tr[0].copy()
            for _ in range(900):
                x = x + (1 / 30) * m.velocity(x)[0]
            ends.append(np.linalg.norm(x - m.target))
        stats[name] = dict(K=m.gmm.n_components, max_eig=lyap, v_rmse=pol.meta["fit_info"][name]["velocity_rmse"],
                           conv=float(np.mean(np.array(ends) < 0.002)), v_max=p.v_max, v_min=p.v_min,
                           target=m.target)
        allp = np.vstack(L)
        for col, (i, j, lab) in enumerate(((0, 2, ("x", "z")), (0, 1, ("x", "y")))):
            ax = axs[row, col]
            lo, hi = np.percentile(allp, 1, axis=0) - 0.03, np.percentile(allp, 99, axis=0) + 0.03
            xs, ys = np.linspace(lo[i], hi[i], 60), np.linspace(lo[j], hi[j], 60)
            XX, YY = np.meshgrid(xs, ys)
            G = np.tile(m.target, (XX.size, 1))
            G[:, i], G[:, j] = XX.ravel(), YY.ravel()
            V = m.velocity(G)
            Vl = m.lyapunov(G).reshape(XX.shape)
            ax.contour(xs * 100, ys * 100, Vl, levels=12, colors="0.75", linewidths=0.6)
            for tr in L[::6]:
                ax.plot(tr[:, i] * 100, tr[:, j] * 100, c="0.55", lw=0.4)
            sp = np.hypot(V[:, i], V[:, j]).reshape(XX.shape)
            strm = ax.streamplot(xs * 100, ys * 100, V[:, i].reshape(XX.shape), V[:, j].reshape(XX.shape),
                                 color=sp, cmap="viridis", density=1.2, linewidth=0.8)
            ax.plot(m.target[i] * 100, m.target[j] * 100, "*", c="gold", ms=14, mec="k")
            frame = "cube" if name == "approach_grasp" else "box"
            ax.set_title(f"{name}, {frame} frame, slice through the attractor: {lab[0]}–{lab[1]}", fontsize=9)
            ax.set_xlabel(f"{lab[0]} [cm]"), ax.set_ylabel(f"{lab[1]} [cm]")
            if lab == ("x", "y"):
                ax.set_aspect("equal")
            plt.colorbar(strm.lines, ax=ax, shrink=0.8, label="speed [m/s]")
    fig.suptitle("Stable LPV-DS: streamlines (colour = speed) and Lyapunov level sets (grey ellipses); ★ = attractor",
                 fontsize=10)
    fig.tight_layout(); fig.savefig(resolve_path("docs/figures/lpvds_field.png"), dpi=100); plt.close(fig)

    Lr = ["# LPV-DS policy\n", "_Generated by `scripts/train_lpvds.py`._\n",
          "## Model\n",
          "ẋ = Σ_k γ_k(x) A_k (x − x*) per primitive, in its goal frame (approach: cube; transport: box). Stability "
          "is built into the parameterization: P = QQᵀ + εI, A_k = P⁻¹B_k with B_k + B_kᵀ = −2(L_kL_kᵀ + εI) ≺ 0, so "
          "V = (x − x*)ᵀP(x − x*) decreases for any fitted parameters (no SDP solver needed). Scheduling GMM on "
          "[position, scaled velocity direction] (a lightweight physically-consistent clustering); K by BIC. "
          "Heading and pitch: stable scalar DS with the same γ(x). Gripper: E[g | distance to the attractor], held "
          "open within 2 cm and closed on arrival. Speed: positive state-dependent scaling (floor near the target, "
          "ceiling at the 99th percentile), which keeps the flow direction and hence stability.\n",
          "| primitive | K | max eig(AᵀP + PA) | velocity RMSE [m/s] | demo starts converging (< 2 mm) | speed floor / ceiling [m/s] |",
          "|---|---|---|---|---|---|"]
    for name, s in stats.items():
        Lr.append(f"| {name} | {s['K']} | {s['max_eig']:.4f} | {s['v_rmse']:.3f} | {100 * s['conv']:.0f} % | "
                  f"{s['v_min']:.3f} / {s['v_max']:.3f} |")
    Lr += ["", "![](figures/lpvds_field.png)\n",
           "The velocity RMSE is large relative to the demonstrated speeds: a first-order field of the position "
           "cannot represent motions whose velocity depends on the phase (the approach first rises, then descends "
           "onto the cube). What the model guarantees instead is convergence to the attractor from anywhere, and a "
           "reaction to the current state. Offline comparison: `evaluation_report.md`; robustness: "
           "`perturbation_report.md`."]
    resolve_path("docs/lpvds_report.md").write_text("\n".join(Lr) + "\n", encoding="utf-8")
    print(stats)


if __name__ == "__main__":
    main()
