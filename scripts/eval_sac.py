#!/usr/bin/env python
"""Evaluate the SAC policies against the TP-GMM on the single-cube task and write docs/sac_report.md.

Policies: the TP-GMM alone (residual environment with zero correction), SAC residual on the TP-GMM
and SAC from scratch (``best_model.zip`` of each run). Conditions: ``nominal`` = the training
distribution (domain randomization, 3 mm perception noise) and ``noise8`` = 8 mm perception noise
(the median error of the real vision pipeline). Same seeds for every policy; deterministic actions.

    python scripts/eval_sac.py --episodes 200 --workers 4
"""

from __future__ import annotations

import argparse
import os
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "1")

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from so101_tpgmm.config import load_config, resolve_path  # noqa: E402

LABEL = {"tpgmm": "TP-GMM alone", "sac_residual": "SAC residual on TP-GMM", "sac_scratch": "SAC from scratch"}
COND = {"nominal": {}, "noise8": {"cube_obs_noise_mm": 8.0, "cube_obs_noise_yaw_deg": 6.0}}


def _run(job):
    import torch
    from stable_baselines3 import SAC

    from so101_tpgmm.rl.sim_env import SO101PickPlaceEnv

    torch.set_num_threads(1)
    policy, cond, seeds, config = job
    cfg = load_config(config, [])
    cfg["rl"].update(COND[cond])
    mode = "scratch" if policy == "sac_scratch" else "residual"
    env = SO101PickPlaceEnv(cfg, mode, randomize=True)
    model = None
    if policy != "tpgmm":
        model = SAC.load(resolve_path(cfg["rl"]["models_dir"]) / f"{mode}_s0" / "best_model.zip", device="cpu")
    rows = []
    for sd in seeds:
        obs, _ = env.reset(seed=int(sd))
        ret, n, grasped = 0.0, 0, False
        while True:
            a = np.zeros(5, np.float32) if model is None else model.predict(obs, deterministic=True)[0]
            obs, r, te, tu, info = env.step(a)
            ret, n = ret + r, n + 1
            grasped |= bool(info.get("lifted", False))
            if te or tu:
                break
        rows.append(dict(policy=policy, condition=cond, seed=int(sd), success=bool(info["success"]), lifted=grasped,
                         steps=n, seconds=n / cfg["rl"]["agent_hz"], ret=ret, unstable=bool(info.get("sim_unstable"))))
    return rows


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=None)
    ap.add_argument("--episodes", type=int, default=200)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--policies", nargs="*", default=list(LABEL))
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args()
    cfg = load_config(args.config, [])
    out = resolve_path("outputs/sim/sac_eval.csv")
    if not args.report_only:
        seeds = np.arange(50_000, 50_000 + args.episodes)
        chunks = np.array_split(seeds, max(1, args.workers))
        jobs = [(p, c, ch, args.config) for p in args.policies for c in COND for ch in chunks]
        with ProcessPoolExecutor(args.workers) as ex:
            rows = [r for rr in ex.map(_run, jobs) for r in rr]
        pd.DataFrame(rows).to_csv(out, index=False)
    df = pd.read_csv(out)
    write_report(df, cfg)


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def write_report(df: pd.DataFrame, cfg: dict) -> None:
    import subprocess

    subprocess.run([sys.executable, str(Path(__file__).with_name("plot_sac.py"))], check=False)
    root = resolve_path(cfg["rl"]["models_dir"])
    L = ["# SAC on the SO-101 pick-and-place\n", "_Generated by `scripts/eval_sac.py` (training: `scripts/train_sac.py`)._\n",
         "## Setup\n",
         "- **Environment** (`so101_tpgmm/rl/`): the MuJoCo scene of `mujoco_sim.md` (official SO-101 model, finger "
         "boxes, table plane in FK coordinates, contact physics, 0.5 ms steps), one cube per episode drawn from the "
         "demonstrated workspace. The agent acts at 10 Hz; each action becomes a TCP target → IK (warm-started, "
         "joint rate limit) → joint commands interpolated at 30 Hz to the position servos, as on the robot.",
         "- **Observation** (25/31-D, all available on the real robot): measured joints and gripper, TCP and "
         "heading by FK, cube pose from one camera snapshot at the start (no tracking), release point, commanded "
         "target, time; residual: also the TP-GMM's current target and heading.",
         f"- **Actions**: *from scratch*: Δxyz (≤ {cfg['rl']['max_step_m'] * 100:.0f} cm per step), Δheading "
         f"(≤ {cfg['rl']['max_yaw_step_deg']}°), gripper command. *Residual*: offsets added to the TP-GMM plan "
         f"(≤ {cfg['rl']['residual_m'] * 100:.0f} cm, ≤ {cfg['rl']['residual_yaw_deg']}°); the gripper follows the "
         "TP-GMM (see *Residual: what went wrong first*). Zero action = the TP-GMM.",
         "- **Reward** (staged, robosuite-like): reach 0.1·(1 − tanh 10d), grasp 0.35, lift/carry 0.35–0.5, success "
         "= cube released inside the box → 1 per remaining step (the episode ends); −0.05 for an unreachable target; "
         f"residual: −{cfg['rl']['residual_action_penalty']}·mean(a²).",
         "- **Domain randomization** per episode: table height ±4 mm, cube mass 20–60 g, friction 0.8–1.5, servo "
         "stiffness ±20 %, perception noise 3 mm / 3°.",
         "- **SAC** (Stable-Baselines3): 256×256 networks, γ = 0.98, batch 256, 2 parallel environments. Residual: "
         "zero-initialized mean (starts as the TP-GMM), exploration σ = 0.2, critic-only warm-up of 50 k steps, "
         "actor learning rate ×0.1, fixed entropy coefficient 0.002, 2 updates per step.", ""]
    L += ["## Learning curves\n", "![](figures/sac_learning_curves.png)\n"]
    L += ["## Evaluation (single cube, deterministic policies, same seeds)\n",
          "| condition | policy | success [95 % CI] | cube lifted | mean time [s] | episodes |", "|---|---|---|---|---|---|"]
    df = df.assign(_c=df.condition.map({c: i for i, c in enumerate(COND)}),
                   _p=df.policy.map({p: i for i, p in enumerate(LABEL)})).sort_values(["_c", "_p", "seed"])
    for (c, p), d in df.groupby(["condition", "policy"], sort=False):
        k, n = int(d.success.sum()), len(d)
        lo, hi = wilson(k, n)
        L.append(f"| {c} | {LABEL.get(p, p)} | {100 * k / n:.1f} % [{100 * lo:.0f}, {100 * hi:.0f}] | "
                 f"{100 * d.lifted.mean():.0f} % | {d.seconds[d.success].mean():.1f} | {n} |")
    L.append("")
    # paired comparison residual vs TP-GMM
    for c in df.condition.unique():
        a = df[(df.condition == c) & (df.policy == "tpgmm")].set_index("seed").success
        b = df[(df.condition == c) & (df.policy == "sac_residual")].set_index("seed").success
        if len(a) and len(b):
            j = a.index.intersection(b.index)
            win, loss = int((b[j] & ~a[j]).sum()), int((a[j] & ~b[j]).sum())
            from scipy.stats import binomtest

            pv = binomtest(win, win + loss).pvalue if win + loss else 1.0
            L.append(f"- **{c}:** SAC residual succeeds where the TP-GMM fails in {win} episodes, and the opposite in "
                     f"{loss} (exact binomial test on the discordant pairs, p = {pv:.2g}).")
    L += ["", "## Residual: what went wrong first\n",
          "1. **Initial exploration noise.** In SB3, `log_std_init` only applies with gSDE; without it the initial σ is "
          "~1 and the noise alone broke the TP-GMM (4 % success while collecting, 93 % deterministic). Fixed by "
          "initializing the log-σ layer.",
          "2. **Actor jumps after the warm-up.** With σ = 0.05, a 30 k critic warm-up and the full learning rate, the "
          "actor moved to corrections the critic had never seen: 93 % → 33 %. A slower actor (×0.1) and wider "
          "exploration were not enough on their own (93 % → 53 %).",
          "3. **A cliff in the gripper dimension.** A constant +9 gripper units while holding leaves the jaws wider "
          "than the cube (2/20 successes vs 20/20); ±1 cm in position costs much less (11–19/20). Letting the "
          "gripper follow the TP-GMM, with finer position/heading corrections, a fixed entropy coefficient and a "
          "larger action penalty, made the residual stable (dip to 55 % while collecting at the end of the warm-up, "
          "back to 92–96 %).", "",
          "## SAC from scratch\n",
          "Same environment and reward, no prior. See the learning curve: pick-and-place from scratch with a staged "
          "reward and 10 Hz control needs on the order of 10⁶ steps (≈ 28 h of robot time), which is why, on the "
          "real robot, only the residual variant (or fine-tuning a simulation policy) is realistic.", "",
          "## On the real robot\n",
          "`scripts/run_sac_real.py` runs the same observation/action loop on the SO-101 (`so101_tpgmm/rl/real_env.py`): "
          "cube from the fixed camera, converted to the finger-midpoint convention of the simulation "
          "(`rl.vision_to_finger_heading_mm`, measured on the 368 demonstrated grasps), joint commands at 30 Hz with "
          "LeRobot's per-command limit, tracking-error abort, operator-labelled success; `--finetune N` keeps "
          "training on real episodes, with a measurable grasp reward (jaws stopped open by the cube).", ""]
    runs = sorted(p.name for p in root.iterdir() if (p / "eval.csv").exists()) if root.exists() else []
    L.append("Runs: " + ", ".join(f"`{r}`" for r in runs) + " (in `" + cfg["rl"]["models_dir"] + "`, not versioned).")
    resolve_path("docs/sac_report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(df.groupby(["condition", "policy"]).success.mean())


if __name__ == "__main__":
    main()
