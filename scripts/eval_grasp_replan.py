#!/usr/bin/env python
"""Grasp verification and replanning in MuJoCo: how often is a missed grasp detected, and what does
replanning recover?

Three random cubes per episode (as in ``simulate_mujoco.py``), the TP-GMM (or ``--policy``), pure contact
physics, the real follower's gripper command (squeeze while holding). For each perception-noise level, the
same layouts are run without verification (``replan 0``: open loop, the gripper is never checked) and with
verification + up to ``--retries`` replans. Reports delivered cubes, cubes in the box, attempts, and the
detector's confusion matrix against the simulator's ground truth (cube > 2 cm above where it was).

    MUJOCO_GL=egl python scripts/eval_grasp_replan.py --episodes 30 --noise-mm 0 8 15 --workers 4

Writes ``outputs/sim/grasp_replan.csv`` and ``docs/grasp_check.md``.
"""

from __future__ import annotations

import argparse
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from so101_tpgmm.config import load_config, resolve_path  # noqa: E402

_W: dict = {}


def _setup(config, overrides, policy):
    from so101_tpgmm.kinematics.ik import ik_from_config
    from so101_tpgmm.policies import load_policy
    from so101_tpgmm.sim.episode import FingerGeometry
    from so101_tpgmm.sim.scene import SceneSpec

    cfg = load_config(config, overrides)
    xml = resolve_path(cfg["sim"]["robot_dir"]) / "so101_new_calib.xml"
    f = pd.read_csv(resolve_path(cfg["vision"]["frames_csv"]))
    _W.update(cfg=cfg, xml=xml, ik=ik_from_config(cfg), demo_xy=f[["fk_x", "fk_y"]].dropna().to_numpy(),
              geom=FingerGeometry(SceneSpec.from_config(cfg, xml, [])), policy=load_policy(cfg, policy))


def _job(args):
    seed, noise, retries = args
    from so101_tpgmm.sim.episode import run_episode, sample_cubes
    from so101_tpgmm.sim.scene import SceneSpec

    cfg = _W["cfg"]
    spec = SceneSpec.from_config(cfg, _W["xml"], sample_cubes(np.random.default_rng(seed), _W["demo_xy"], cfg))
    rng = np.random.default_rng(10_000 + seed)  # same noise draws for both arms up to the first replan
    outs, _ = run_episode(_W["policy"], _W["ik"], cfg, spec, _W["geom"], rng, noise_mm=noise, grasp_mode="contact",
                          replan=retries if retries > 0 else None, robot_gripper=True)
    rows = []
    for o in outs:
        rows.append(dict(seed=seed, noise_mm=noise, retries=retries, color=o.color, status=o.status,
                         delivered=bool(o.released_over_box or o.in_box), in_box=o.in_box, lifted=o.lifted,
                         attempts=o.attempts, checks=o.checks))
    return rows


def render(seed: int, noise: float, retries: int, out: Path) -> None:
    """GIF of one verified episode (perspective view): a missed grasp, the retreat and the replan."""
    import mujoco
    from PIL import Image

    from so101_tpgmm.sim.episode import run_episode, sample_cubes
    from so101_tpgmm.sim.scene import SceneSpec

    cfg = _W["cfg"]
    spec = SceneSpec.from_config(cfg, _W["xml"], sample_cubes(np.random.default_rng(seed), _W["demo_xy"], cfg))
    cam = mujoco.MjvCamera()
    cam.lookat[:] = [0.2, 0.06, 0.0]
    cam.distance, cam.azimuth, cam.elevation = 0.8, -140.0, -38.0
    frames = []

    def grab(sim):
        sim.renderer.update_scene(sim.data, camera=cam)
        frames.append(Image.fromarray(sim.renderer.render()).resize((320, 240)))

    outs, _ = run_episode(_W["policy"], _W["ik"], cfg, spec, _W["geom"], np.random.default_rng(10_000 + seed),
                          noise_mm=noise, grasp_mode="contact", render=(480, 640), frame_callback=grab,
                          render_every=3, replan=retries, robot_gripper=True)
    small = [f.quantize(colors=96, method=Image.Quantize.MEDIANCUT) for f in frames]
    out.parent.mkdir(parents=True, exist_ok=True)
    small[0].save(out, save_all=True, append_images=small[1:], duration=100, loop=0, optimize=True)
    print(f"{out}: " + "; ".join(f"{o.color} {o.attempts} attempt(s), checks {[c['pred'] for c in o.checks]}, "
                                 f"{'delivered' if o.in_box or o.released_over_box else 'not delivered'}" for o in outs))


def report(df: pd.DataFrame, policy: str, out_md: Path) -> str:
    L = [f"# Grasp verification and replanning (MuJoCo, `{policy}`)\n",
         "_Generated by `scripts/eval_grasp_replan.py`. Three random cubes per episode, contact physics, the real "
         "follower's gripper command (squeeze while holding); the same layouts and perception-noise draws for "
         "both arms. **Open loop**: the plan is executed without checking the grasp (as `so101_runner` does). "
         "**Verified**: the grasp is checked and a missed cube is re-detected and planned again._\n",
         "## Delivered cubes\n",
         "| perception noise σ | open loop: delivered | verified + replan: delivered | open loop: in box | "
         "verified: in box | verified: attempts per cube (mean) | cubes needing a replan |",
         "|---|---|---|---|---|---|---|"]
    for nz, g in df.groupby("noise_mm"):
        a, b = g[g.retries == 0], g[g.retries > 0]
        L.append(f"| {nz:.0f} mm | {100 * a.delivered.mean():.0f} % ({a.delivered.sum()}/{len(a)}) | "
                 f"**{100 * b.delivered.mean():.0f} %** ({b.delivered.sum()}/{len(b)}) | {100 * a.in_box.mean():.0f} % | "
                 f"{100 * b.in_box.mean():.0f} % | {b.attempts.mean():.2f} | {(b.attempts > 1).sum()} |")
    ch = pd.DataFrame([c | {"noise_mm": r.noise_mm} for r in df[df.retries > 0].itertuples() for c in r.checks])
    if len(ch):
        tp = int((ch.pred & ch.true).sum())
        tn = int((~ch.pred & ~ch.true).sum())
        fp = int((ch.pred & ~ch.true).sum())
        fn = int((~ch.pred & ch.true).sum())
        L += ["", "## Detector against the simulator's ground truth\n",
              f"{len(ch)} grasp checks (all noise levels). Ground truth: the cube is more than 2 cm above where it was "
              "at the check (it is being lifted).\n",
              "| | truly held | truly missed |", "|---|---|---|",
              f"| detected held | {tp} | {fp} |", f"| detected missed | {fn} | {tn} |", "",
              f"Measured − commanded gripper at the check: held median "
              f"{(ch.g_meas - ch.g_cmd)[ch.true].median():.1f} (min {(ch.g_meas - ch.g_cmd)[ch.true].min():.1f}), "
              f"missed median {(ch.g_meas - ch.g_cmd)[~ch.true].median():.1f} "
              f"(max {(ch.g_meas - ch.g_cmd)[~ch.true].max():.1f}); threshold `grasp_check.min_margin`."]
    L += ["", "## The signals (real data)\n",
          "Measured on dataset3 (`so101_tpgmm/grasp.py`):\n",
          "| signal | holding a cube | gripper closed empty | threshold |", "|---|---|---|---|",
          "| follower − leader gripper | median 19.1 (399 cycles) | 0.5 s after closing: median 0.7, max 6.6 (398); "
          "0.17 s after: up to 41 (jaws still moving) | `min_margin` 8, checked `settle_s` 0.5 s after the command "
          "reaches its hold value |",
          "| the three demonstrations with a missed grasp | — | −0.8, 0.7, −0.2 | |",
          "| wrist camera: largest cube-coloured blob / ROI | 0.5 s after closing: median 0.55, min 0.32; 1.3 s: "
          "median 0.54, 2 of 79 below 0.25 | after the release: 0.00 (79 of 79) | `wrist.min_blob` 0.15 |",
          "",
          "On the robot the executor sends the squeeze command (`inference.gripper_command.hold_command`, 2): a held "
          "cube keeps the jaws near 20, an empty gripper reaches ~2.",
          ""]
    if "--video" in " ".join(sys.argv) or resolve_path("docs/figures/sim_grasp_replan.gif").exists():
        L += ["![A missed grasp, the retreat and the replan](figures/sim_grasp_replan.gif)\n"]
    L += ["", "## Notes\n",
          "- The re-detection draws a new perception error, independent of the first one. The real camera's error "
          "is partly a bias that repeats from photo to photo (calibration), so on the robot a replan from the same "
          "camera can repeat the same miss: the gain here is an upper bound for that part of the error.",
          "- A cube knocked into the box or off the table during a miss is not attempted again.",
          "- Signals and thresholds: `so101_tpgmm/grasp.py` (measured on dataset3 and in MuJoCo)."]
    text = "\n".join(L) + "\n"
    out_md.write_text(text, encoding="utf-8")
    return text


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=None)
    ap.add_argument("--set", nargs="*", default=[])
    ap.add_argument("--policy", default="segmented")
    ap.add_argument("--episodes", type=int, default=30)
    ap.add_argument("--noise-mm", type=float, nargs="*", default=[0.0, 8.0, 15.0])
    ap.add_argument("--retries", type=int, default=2)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--video", type=float, nargs=2, metavar=("SEED", "NOISE_MM"), default=None,
                    help="only render the verified episode SEED at NOISE_MM to docs/figures/sim_grasp_replan.gif")
    args = ap.parse_args()
    if args.video:
        _setup(args.config, args.set, args.policy)
        render(int(args.video[0]), args.video[1], args.retries, resolve_path("docs/figures/sim_grasp_replan.gif"))
        return
    out_csv = resolve_path("outputs/sim/grasp_replan.csv")
    if args.report_only:
        df = pd.read_pickle(out_csv.with_suffix(".pkl"))
    else:
        jobs = [(s, n, r) for n in args.noise_mm for r in (0, args.retries) for s in range(args.episodes)]
        with Pool(args.workers, initializer=_setup, initargs=(args.config, args.set, args.policy)) as pool:
            rows = []
            for k, part in enumerate(pool.imap_unordered(_job, jobs), 1):
                rows += part
                if k % 10 == 0:
                    print(f"  {k}/{len(jobs)} episodes", flush=True)
        df = pd.DataFrame(rows)
        out_csv.parent.mkdir(parents=True, exist_ok=True)
        df.drop(columns="checks").to_csv(out_csv, index=False)
        df.to_pickle(out_csv.with_suffix(".pkl"))
    print(report(df, args.policy, resolve_path("docs/grasp_check.md")))


if __name__ == "__main__":
    main()
